/**
 * Builds the shippable plugin directory.
 *
 * wordpress.org forbids loading executable code from another server, so the
 * widget bundle and the PHP SDK are copied into `kaaljyoti/` rather than
 * fetched at runtime or installed with Composer (design decision 1). Both
 * copies are build outputs: they are gitignored, and this script is the only
 * thing that writes them. The bundle is minified, so its readable source and
 * build go in too, as `widgets-src/` (WordPress.org's guideline 4).
 *
 *   node tool/build.mjs          copy the bundle, its source and the SDK in
 *   node tool/build.mjs --zip    …and write dist/kaaljyoti.zip
 */

import { execFileSync } from 'node:child_process';
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pluginRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(pluginRoot, '..', '..');
const shipped = path.join(pluginRoot, 'kaaljyoti');

const widgetDist = path.join(repoRoot, 'packages', 'widgets', 'dist');
const widgetManifest = path.join(widgetDist, 'cdn-files.json');
const sdkSource = path.join(repoRoot, 'packages', 'sdk-php', 'src');
const sdkPackageJson = path.join(repoRoot, 'packages', 'sdk-php', 'package.json');
const sdkComposerJson = path.join(repoRoot, 'packages', 'sdk-php', 'composer.json');

const widgetPackage = path.join(repoRoot, 'packages', 'widgets');

const bundleTarget = path.join(shipped, 'assets', 'widgets');
const sourceTarget = path.join(shipped, 'widgets-src');
const sdkTarget = path.join(shipped, 'vendor', 'kaaljyoti-sdk');

const SDK_AUTOLOADER = String.raw`<?php
/**
 * PSR-4 autoloader for the bundled Kaal Jyoti PHP SDK.
 *
 * GENERATED by plugins/wordpress/tool/build.mjs — do not edit by hand.
 *
 * The SDK is copied in rather than installed with Composer, so a site with no
 * autoloader of its own can still use it. A site that already provides
 * Kaaljyoti\Client keeps its own copy: the plugin checks before requiring
 * this file, and this file registers nothing twice.
 */

defined( 'ABSPATH' ) || exit;

if ( ! function_exists( 'kaal_jyoti_sdk_autoload' ) ) {
	/**
	 * Loads one class of the bundled SDK.
	 *
	 * @param string $class_name The fully qualified class name PHP is looking for.
	 * @return void
	 */
	function kaal_jyoti_sdk_autoload( $class_name ) {
		$prefix = 'Kaaljyoti\\';

		if ( 0 !== strpos( $class_name, $prefix ) ) {
			return;
		}

		$relative = substr( $class_name, strlen( $prefix ) );
		$path     = __DIR__ . '/src/' . str_replace( '\\', '/', $relative ) . '.php';

		if ( is_readable( $path ) ) {
			require_once $path;
		}
	}

	spl_autoload_register( 'kaal_jyoti_sdk_autoload' );
}
`;

/** @param {string} target @returns {Promise<boolean>} */
async function exists(target) {
  try {
    await stat(target);
    return true;
  } catch {
    return false;
  }
}

/** @param {string} message @returns {never} */
function fail(message) {
  console.error(`build.mjs: ${message}`);
  process.exit(1);
}

/**
 * The loader and every chunk it can load (`dist/cdn-files.json` lists them),
 * flat in `assets/widgets/`. Chunks are content-hashed, so the ones a
 * previous build left behind are removed first rather than shipped forever.
 */
async function copyWidgetBundle() {
  if (!(await exists(widgetManifest))) {
    fail(
      `the widget bundle is missing at ${path.relative(repoRoot, widgetDist)}.\n` +
        '  Build it first: pnpm --filter @kaaljyoti/widgets run build',
    );
  }
  const manifest = JSON.parse(await readFile(widgetManifest, 'utf8'));

  await mkdir(bundleTarget, { recursive: true });
  for (const name of await readdir(bundleTarget)) {
    if (name === 'v1.js' || /^kj-.*\.js$/.test(name)) await rm(path.join(bundleTarget, name));
  }
  const files = [manifest.loader, ...manifest.chunks];
  let bytes = 0;
  for (const name of files) {
    await cp(path.join(widgetDist, name), path.join(bundleTarget, name));
    bytes += (await stat(path.join(bundleTarget, name))).size;
  }

  console.log(
    `  assets/widgets/             v1.js and ${manifest.chunks.length} chunks, ${(bytes / 1024).toFixed(1)} kB from packages/widgets/dist`,
  );
}

async function copySdk() {
  if (!(await exists(sdkSource))) {
    fail(`the PHP SDK is missing at ${path.relative(repoRoot, sdkSource)}.`);
  }

  await rm(sdkTarget, { recursive: true, force: true });
  await mkdir(sdkTarget, { recursive: true });
  await cp(sdkSource, path.join(sdkTarget, 'src'), { recursive: true });
  await writeFile(path.join(sdkTarget, 'autoload.php'), SDK_AUTOLOADER, 'utf8');

  // The SDK's own composer.json, with the version bundled: what the copy is
  // and what it needs, readable without the repository (WordPress.org asks
  // for a composer.json beside bundled PHP dependencies).
  const { version } = JSON.parse(await readFile(sdkPackageJson, 'utf8'));
  const composer = JSON.parse(await readFile(sdkComposerJson, 'utf8'));
  await writeFile(
    path.join(sdkTarget, 'composer.json'),
    `${JSON.stringify({ name: composer.name, version, ...composer }, null, 2)}\n`,
    'utf8',
  );

  console.log(
    `  vendor/kaaljyoti-sdk/       sdk-php ${version}, with a PSR-4 autoloader and its composer.json`,
  );
}

