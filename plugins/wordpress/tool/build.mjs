/**
 * The readable source of the minified widget files.
 *
 * WordPress.org asks for human-readable code: a minified file has to come
 * with its source, or a link to it. The widget bundle is minified, so its
 * TypeScript and CSS, and the build that turns them into the bundle, ship in
 * `widgets-src/`. The checking tsconfig extends the workspace's base, which
 * is not in the plugin, so a copy of the base goes in beside it.
 */
async function copyWidgetSource() {
  await rm(sourceTarget, { recursive: true, force: true });
  await mkdir(path.join(sourceTarget, 'scripts'), { recursive: true });

  await cp(path.join(widgetPackage, 'src'), path.join(sourceTarget, 'src'), { recursive: true });
  await cp(
    path.join(widgetPackage, 'scripts', 'build.mjs'),
    path.join(sourceTarget, 'scripts', 'build.mjs'),
  );
  for (const name of ['package.json', 'LICENSE', 'tsconfig.build.json']) {
    await cp(path.join(widgetPackage, name), path.join(sourceTarget, name));
  }
  await cp(
    path.join(repoRoot, 'tsconfig.base.json'),
    path.join(sourceTarget, 'tsconfig.base.json'),
  );

  const tsconfig = (await readFile(path.join(widgetPackage, 'tsconfig.json'), 'utf8'))
    .replace('"../../tsconfig.base.json"', '"./tsconfig.base.json"')
    .replace(/"include": \[[^\]]*\]/, '"include": ["src/**/*.ts", "scripts/**/*.mjs"]');
  await writeFile(path.join(sourceTarget, 'tsconfig.json'), tsconfig, 'utf8');
  await writeFile(path.join(sourceTarget, 'README.txt'), WIDGET_SOURCE_README, 'utf8');

  const files = (await readdir(sourceTarget, { recursive: true, withFileTypes: true })).filter(
    (entry) => entry.isFile(),
  ).length;
  console.log(
    `  widgets-src/                ${files} files: the readable source of assets/widgets/`,
  );
}

/** Patterns `zip` leaves out of `kaaljyoti/`. */
const ZIP_EXCLUDES = [
  '*.DS_Store',
  '*/.*',
  '*/node_modules/*',
  '*/tests/*',
  '*/dist/*',
  '*.map',
  '*.log',
];

/** What must never be in the zip, checked on its listing after it is written. */
const FORBIDDEN_IN_ZIP = [
  /(^|\/)\.[^/]+/,
  /(^|\/)node_modules\//,
  /(^|\/)tests?\//,
  /(^|\/)wporg-assets\//,
  /(^|\/)(composer\.(json|lock)|phpunit\.xml|phpcs\.xml(\.dist)?)$/,
  /\.(map|log|zip)$/,
];

async function writeZip() {
  const distDir = path.join(pluginRoot, 'dist');
  const zipPath = path.join(distDir, 'kaaljyoti.zip');

  await mkdir(distDir, { recursive: true });
  await rm(zipPath, { force: true });

  // Only `kaaljyoti/` goes in, so the dev tree's `vendor/` — phpunit, phpcs
  // and the rest — the tests and the directory screenshots in `wporg-assets/`
  // are outside the zip by construction. The exclusions catch what an editor
  // or an install could leave inside it.
  execFileSync('zip', ['-r', '-q', zipPath, 'kaaljyoti', '-x', ...ZIP_EXCLUDES], {
    cwd: pluginRoot,
    stdio: 'inherit',
  });

  const listing = execFileSync('unzip', ['-Z1', zipPath], { encoding: 'utf8' }).trim().split('\n');
  const stray = listing.filter((name) => FORBIDDEN_IN_ZIP.some((pattern) => pattern.test(name)));
  if (stray.length > 0) fail(`the zip holds files that must not ship:\n  ${stray.join('\n  ')}`);
  const files = listing.filter((name) => !name.endsWith('/')).length;

  const { size } = await stat(zipPath);
  console.log(`  dist/kaaljyoti.zip         ${(size / 1024).toFixed(1)} kB, ${files} files`);
}

console.log('Kaal Jyoti for WordPress — building kaaljyoti/');
await copyWidgetBundle();
await copySdk();
await copyWidgetSource();

if (process.argv.includes('--zip')) {
  await writeZip();
}

console.log('Done.');
