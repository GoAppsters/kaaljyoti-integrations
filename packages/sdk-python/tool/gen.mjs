/**
 * A resolved Python type.
 *
 * `kind` drives the `from_dict` / `to_dict` expressions; `render` is what the
 * field is annotated as. `nullable` is tracked separately so a
 * `list[T] | None` knows its element type is not itself optional.
 */
function type(kind, extra = {}) {
  return { kind, nullable: false, ...extra };
}

function render(t) {
  let base;
  switch (t.kind) {
    case 'string':
      base = 'str';
      break;
    case 'int':
      base = 'int';
      break;
    case 'double':
      base = 'float';
      break;
    case 'bool':
      base = 'bool';
      break;
    case 'stringList':
      base = 'list[str]';
      break;
    case 'stringOrClass':
      base = `str | ${t.name}`;
      break;
    case 'class':
      base = t.name;
      break;
    case 'list':
      base = `list[${render(t.of)}]`;
      break;
    case 'map':
      base = `dict[str, ${render(t.of)}]`;
      break;
    case 'json':
      base = 'dict[str, Any]';
      break;
    case 'any':
      return 'Any';
    default:
      throw new Error(`unknown kind ${t.kind}`);
  }
  return t.nullable ? `${base} | None` : base;
}

/** True when a value of `t` is already JSON and needs no mapping either way. */
function isPlain(t) {
  return ['string', 'int', 'double', 'bool', 'json', 'any'].includes(t.kind);
}

/** The expression that reads `expr` (an `Any`) as a non-None `t`. */
function readNonNull(t, expr, depth) {
  switch (t.kind) {
    case 'string':
      return `as_str(${expr})`;
    case 'int':
      return `as_int(${expr})`;
    case 'double':
      return `as_float(${expr})`;
    case 'bool':
      return `as_bool(${expr})`;
    case 'stringList':
      return `as_str_list(${expr})`;
    case 'stringOrClass':
      return `${expr} if isinstance(${expr}, str) else ${t.name}.from_dict(as_dict(${expr}))`;
    case 'class':
      return `${t.name}.from_dict(as_dict(${expr}))`;
    case 'json':
      return `as_dict(${expr})`;
    case 'any':
      return expr;
    case 'list': {
      const e = `e${depth}`;
      const inner = read(t.of, e, depth + 1);
      return inner === e ? `as_list(${expr})` : `[${inner} for ${e} in as_list(${expr})]`;
    }
    case 'map': {
      const k = `k${depth}`;
      const v = `v${depth}`;
      const inner = read(t.of, v, depth + 1);
      return inner === v
        ? `as_dict(${expr})`
        : `{${k}: ${inner} for ${k}, ${v} in as_dict(${expr}).items()}`;
    }
    default:
      throw new Error(`unknown kind ${t.kind}`);
  }
}

/** The expression that reads `expr` as `t`, optionality included. */
function read(t, expr, depth = 0) {
  if (!t.nullable) return readNonNull(t, expr, depth);
  if (t.kind === 'any') return expr;
  const simple = {
    string: 'as_str_or_none',
    int: 'as_int_or_none',
    double: 'as_float_or_none',
    bool: 'as_bool_or_none',
    json: 'as_dict_or_none',
  };
  if (simple[t.kind]) return `${simple[t.kind]}(${expr})`;
  const inner = readNonNull(t, expr, depth);
  return `None if ${expr} is None else ${t.kind === 'stringOrClass' ? `(${inner})` : inner}`;
}

/** The expression that turns `expr`, a non-None `t`, back into JSON. */
function writeNonNull(t, expr, depth) {
  switch (t.kind) {
    case 'class':
      return `${expr}.to_dict()`;
    case 'stringList':
      // A single language goes out as the string the gateway documents.
      return `${expr}[0] if len(${expr}) == 1 else list(${expr})`;
    case 'stringOrClass':
      return `${expr} if isinstance(${expr}, str) else ${expr}.to_dict()`;
    case 'list': {
      if (isPlain(t.of)) return `list(${expr})`;
      const e = `e${depth}`;
      return `[${write(t.of, e, depth + 1)} for ${e} in ${expr}]`;
    }
    case 'map': {
      if (isPlain(t.of)) return `dict(${expr})`;
      const k = `k${depth}`;
      const v = `v${depth}`;
      return `{${k}: ${write(t.of, v, depth + 1)} for ${k}, ${v} in ${expr}.items()}`;
    }
    default:
      return expr;
  }
}

function write(t, expr, depth = 0) {
  if (!t.nullable || isPlain(t)) return writeNonNull(t, expr, depth);
  const inner = writeNonNull(t, expr, depth);
  const wrapped = t.kind === 'stringList' || t.kind === 'stringOrClass';
  return `None if ${expr} is None else ${wrapped ? `(${inner})` : inner}`;
}

