/** `utc_offset` / `UtcOffset` / `utcOffset` → `['utc', 'offset']`. */
function words(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
}

function pascal(name) {
  return words(name)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');
}

/** The attribute a wire key becomes: the key itself wherever Python allows. */
function pyName(wire) {
  let name = /^[a-z_][a-z0-9_]*$/.test(wire)
    ? wire
    : words(wire)
        .map((w) => w.toLowerCase())
        .join('_');
  if (/^[0-9]/.test(name)) name = `n${name}`;
  return RESERVED.has(name) ? `${name}_` : name;
}

/** `whole_sign` → `WHOLE_SIGN`, the name a class constant goes by. */
function constantName(value) {
  return words(value)
    .map((w) => w.toUpperCase())
    .join('_');
}

