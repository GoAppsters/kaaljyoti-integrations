/** A Python string literal. JSON's escapes are all valid Python escapes. */
function quote(text) {
  return JSON.stringify(String(text));
}

/** The line length in `pyproject.toml`, which `ruff check` enforces (E501). */
const WIDTH = 100;

/** `text` broken on spaces into lines of at most `width` characters. */
function wrap(text, width) {
  const out = [];
  let line = '';
  for (const word of text.split(' ')) {
    if (line === '') line = word;
    else if (`${line} ${word}`.length <= width) line = `${line} ${word}`;
    else {
      out.push(line);
      line = word;
    }
  }
  if (line !== '') out.push(line);
  return out;
}

/** A description as docstring lines: trimmed, wrapped, blank lines kept. */
function prose(text, indent) {
  if (!text) return [];
  const width = WIDTH - indent.length - 4;
  const out = [];
  for (const raw of String(text).trim().split('\n')) {
    const line = raw.replace(/\s+$/, '').replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"');
    if (line === '') out.push('');
    else out.push(...wrap(line, width));
  }
  return out;
}

/** A docstring, one line when it fits, otherwise opening and closing alone. */
function docstring(lines, indent) {
  if (lines.length === 0) return [];
  const safe = [...lines];
  // A docstring may not end in a quote: `""""` would close it early.
  if (safe[safe.length - 1].endsWith('"')) safe[safe.length - 1] += ' ';
  if (safe.length === 1 && `${indent}"""${safe[0]}"""`.length <= WIDTH) {
    return [`${indent}"""${safe[0]}"""`];
  }
  return [
    `${indent}"""${safe[0]}`,
    ...safe.slice(1).map((line) => (line ? `${indent}${line}` : '')),
    `${indent}"""`,
  ];
}

