function classDocstring(entry) {
  const lines = prose(entry.description, '    ');
  if (lines.length > 0) lines.push('');
  lines.push(...prose(`Wire shape: \`${entry.origin}\`.`, '    '));
  return docstring(lines, '    ');
}

function emitClass(entry) {
  if (entry.valueType) return emitMapClass(entry);

  const out = ['@dataclass(frozen=True, slots=True)', `class ${entry.name}:`];
  out.push(...classDocstring(entry));
  out.push('');

  const renamed = entry.fields.filter((f) => f.name !== f.wire);
  if (renamed.length > 0) {
    out.push('    _WIRE: ClassVar[dict[str, str]] = {');
    for (const f of renamed) out.push(`        ${quote(f.name)}: ${quote(f.wire)},`);
    out.push('    }');
    out.push('    """Attributes whose wire key is not their own name."""');
    out.push('');
  }

  for (const f of entry.fields) {
    out.push(`    ${f.name}: ${render(f.type)}${f.type.nullable ? ' = None' : ''}`);
    const lines = prose(f.description, '    ');
    if (f.name !== f.wire) {
      if (lines.length > 0) lines.push('');
      lines.push(`Wire key: \`${f.wire}\`.`);
    }
    out.push(...docstring(lines, '    '));
  }
  if (entry.fields.length > 0) out.push('');

  out.push('    @classmethod');
  out.push(`    def from_dict(cls, data: Mapping[str, Any]) -> ${entry.name}:`);
  out.push('        """Read the wire shape, as `json.loads` returns it."""');
  if (entry.fields.length === 0) {
    out.push('        del data');
    out.push('        return cls()');
  } else {
    out.push('        return cls(');
    for (const f of entry.fields) {
      out.push(`            ${f.name}=${read(f.type, `data.get(${quote(f.wire)})`)},`);
    }
    out.push('        )');
  }
  out.push('');

  out.push('    def to_dict(self) -> dict[str, Any]:');
  out.push('        """This value as JSON, with every `None` left out."""');
  out.push('        out: dict[str, Any] = {}');
  for (const f of entry.fields) {
    const self = `self.${f.name}`;
    const target = `out[${quote(f.wire)}]`;
    if (!f.type.nullable) {
      out.push(`        ${target} = ${writeNonNull(f.type, self, 0)}`);
    } else {
      out.push(`        if ${self} is not None:`);
      out.push(`            ${target} = ${writeNonNull({ ...f.type, nullable: false }, self, 0)}`);
    }
  }
  out.push('        return out');
  return out.join('\n');
}

/** A document that is a bare map: the class wraps it and subscripts through. */
function emitMapClass(entry) {
  const value = render(entry.valueType);
  const optional =
    entry.valueType.nullable || entry.valueType.kind === 'any' ? value : `${value} | None`;
  const out = ['@dataclass(frozen=True, slots=True)', `class ${entry.name}:`];
  out.push(...classDocstring(entry));
  out.push('');
  out.push(`    values: dict[str, ${value}]`);
  out.push('    """The document itself, keyed as the API keys it."""');
  out.push('');
  out.push(`    def __getitem__(self, key: str) -> ${value}:`);
  out.push('        """The entry under `key`; `KeyError` when the API left it out."""');
  out.push('        return self.values[key]');
  out.push('');
  out.push(`    def get(self, key: str) -> ${optional}:`);
  out.push('        """The entry under `key`, or `None` when the API left it out."""');
  out.push('        return self.values.get(key)');
  out.push('');
  out.push('    @classmethod');
  out.push(`    def from_dict(cls, data: Mapping[str, Any]) -> ${entry.name}:`);
  out.push('        """Read the wire shape, as `json.loads` returns it."""');
  out.push(`        return cls({k: ${read(entry.valueType, 'v')} for k, v in data.items()})`);
  out.push('');
  out.push('    def to_dict(self) -> dict[str, Any]:');
  out.push('        """This value as JSON: the map itself."""');
  out.push(`        return {k: ${write(entry.valueType, 'v', 1)} for k, v in self.values.items()}`);
  return out.join('\n');
}

/**
 * A holder of the string constants an enum property accepts.
 *
 * Enums stay `str` on the fields themselves — the gateway adds values between
 * SDK releases and an `enum.Enum` would turn that into a crash — but the
 * values it lists today are worth spelling once so callers can autocomplete
 * them instead of quoting a slug from the docs.
 */
function emitConstants(name, description, values) {
  const out = [`class ${name}:`, ...docstring(prose(description, '    '), '    '), ''];
  for (const value of values) {
    out.push(`    ${constantName(value)}: Final = ${quote(value)}`);
  }
  out.push(`    VALUES: Final[tuple[str, ...]] = (${values.map(quote).join(', ')},)`);
  out.push('    """Every value the snapshot lists, in its order."""');
  return out.join('\n');
}

