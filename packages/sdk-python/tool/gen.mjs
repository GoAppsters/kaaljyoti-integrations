function run(command, args, cwd) {
  return new Promise((resolve_, reject) => {
    const child = spawn(command, args, { cwd, stdio: ['inherit', 'ignore', 'inherit'] });
    child.on('error', reject);
    child.on('close', (code) =>
      code === 0 ? resolve_() : reject(new Error(`${command} ${args.join(' ')} exited ${code}`)),
    );
  });
}

/**
 * Write every file into `rel` and format it, inside the package so ruff reads
 * the package's `pyproject.toml`: format, fix what `ruff check` can (import
 * order), and format again so the fixes are laid out the same way.
 */
async function writeAll(rel) {
  const dir = join(packageDir, rel);
  await mkdir(dir, { recursive: true });
  for (const [name, source] of Object.entries(files)) {
    await writeFile(join(dir, name), source);
  }
  await run(ruff, ['format', '--quiet', rel], packageDir);
  await run(ruff, ['check', '--fix', '--quiet', rel], packageDir);
  await run(ruff, ['format', '--quiet', rel], packageDir);
}

const check = process.argv.includes('--check');

if (check) {
  await rm(checkDir, { recursive: true, force: true });
  const differ = [];
  try {
    await writeAll(checkRel);
    for (const name of Object.keys(files)) {
      const wanted = await readFile(join(checkDir, name));
      const current = await readFile(join(outDir, name)).catch(() => null);
      if (current === null) differ.push(`${name} (missing)`);
      else if (!current.equals(wanted)) differ.push(name);
    }
    const extra = (await readdir(outDir).catch(() => [])).filter(
      (n) => n.endsWith('.py') && !(n in files),
    );
    for (const name of extra) differ.push(`${name} (not generated any more)`);
  } finally {
    await rm(checkDir, { recursive: true, force: true });
  }

  if (differ.length > 0) {
    console.error(
      `${outRel} is out of date with openapi/openapi.json:\n` +
        differ.map((name) => `  - ${name}`).join('\n') +
        `\nRun: pnpm --filter sdk-python run gen`,
    );
    process.exit(1);
  }
  console.log(`${outRel} is current (${Object.keys(files).length} files).`);
} else {
  await writeAll(outRel);
  console.log(
    `Wrote ${Object.keys(files).length} files, ${classes.size + 1} classes ` +
      `(+${CONSTANT_HOLDERS.length} constant holders), ${operations.length} operations from openapi ${doc.info.version}.`,
  );
  if (fallbacks.length > 0) {
    console.log('Constructs with no exact Python shape:');
    for (const line of [...new Set(fallbacks)]) console.log(`  - ${line}`);
  }
}
