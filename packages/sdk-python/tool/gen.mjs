/**
 * `openapi/openapi.json` → `src/kaaljyoti/generated/*.py`.
 *
 * Design decision 3: generated frozen dataclasses, our generator. This follows
 * the Dart and PHP generators (`packages/sdk-dart/tool/gen.mjs`,
 * `packages/sdk-php/tool/gen.mjs`) rule for rule — the same `REQUEST_NAMES`
 * table, the same shape-based dedupe so `Birth`, `CalculationOptions` and
 * `TimeWindow` exist once rather than 35 times, the same hand-picked names for
 * the four shapes that dedupe into something a path-derived name would not
 * describe, `LabelledId` shared, `null`-only fields as the widest type the
 * language has (`Any`), `MaitriDocument` as a wrapper around the map it is,
 * and reference rows left untyped. The four SDKs are read side by side, so a
 * shape must not be `ChalitHouses` in Dart and `ChalitDocumentEqual` here.
 *
 * Field names are the wire names, which are already snake_case. The few that
 * are not a usable Python attribute — `from`, and the capitalised planet keys
 * of `TransitScanDocumentNatalPoints` — are renamed (`from_`, `jupiter`), and
 * only those classes carry a `_WIRE` table saying what they were renamed from.
 *
 * What it writes:
 *
 *   src/kaaljyoti/generated/__init__.py     every generated public name
 *   src/kaaljyoti/generated/_json.py        cast helpers and KaaljyotiFormatError
 *   src/kaaljyoti/generated/labelled_id.py  the one shape every document shares
 *   src/kaaljyoti/generated/models.py       every request, document and nested class
 *   src/kaaljyoti/generated/operations.py   the operation table the contract test walks
 *   src/kaaljyoti/generated/version.py      the two version constants
 *
 * The output is committed and formatted with `ruff format` and
 * `ruff check --fix`; `--check` regenerates into `.gen-check/` inside the
 * package (so ruff reads the same `pyproject.toml`), formats that copy the
 * same way, and compares byte for byte, so CI fails on a stale file rather
 * than shipping models that describe an API we no longer have.
 *
 * Usage: `node tool/gen.mjs [--check]`. `RUFF` overrides the ruff binary
 * (default `.venv/bin/ruff`, else `ruff` on PATH, as CI installs it with pip
 * and has no `.venv`).
 */

