function quote(text) {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
}

/** A description, as `///` lines, with the blank lines OpenAPI allows kept. */
function docComment(text, indent = '') {
  if (!text) return [];
  return String(text)
    .trim()
    .split('\n')
    .map((line) => line.replace(/\s+$/, ''))
    .map((line) => (line ? `${indent}/// ${line}` : `${indent}///`));
}

