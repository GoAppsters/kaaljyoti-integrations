const operations = [];
for (const [path, item] of Object.entries(doc.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!op.operationId) continue;
    const id = op.operationId;
    const body = bodyOf(op);
    let requestType = null;
    if (body) {
      const name = REQUEST_NAMES[id];
      if (!name) throw new Error(`${id} has a request body but no name in REQUEST_NAMES`);
      requestType = defineClass(body, name, `${method.toUpperCase()} ${path} body`);
    }

    let documentType = null;
    const ok = okOf(op);
    if (ok && !OPERATIONS_WITHOUT_DOCUMENT.has(id)) {
      const data = ok.properties?.data ?? ok;
      const name = INLINE_DOCUMENT_NAMES[id];
      documentType = data.$ref
        ? refName(data.$ref)
        : defineClass(
            data,
            name ?? `${pascal(id)}Document`,
            `${method.toUpperCase()} ${path} data`,
          );
    }
    const metaName = INLINE_META_NAMES[id];
    if (metaName && ok?.properties?.meta && !ok.properties.meta.$ref) {
      defineClass(ok.properties.meta, metaName, `${method.toUpperCase()} ${path} meta`);
    }

    operations.push({
      id,
      method: method.toUpperCase(),
      path,
      tag: op.tags?.[0] ?? '',
      requestType,
      documentType,
    });
  }
}

