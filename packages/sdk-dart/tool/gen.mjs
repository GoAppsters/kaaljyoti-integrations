function emitClass(entry) {
  const out = [];
  out.push(...docComment(entry.description));
  if (entry.description) out.push('///');
  out.push(`/// Wire shape: \`${entry.origin}\`.`);
  out.push(`class ${entry.name} {`);

  if (entry.valueType) return emitMapClass(entry, out);

  out.push(`  const ${entry.name}({`);
  for (const f of entry.fields) {
    out.push(`    ${f.type.nullable ? '' : 'required '}this.${f.name},`);
  }
  out.push('  });');
  out.push('');

  out.push(`  factory ${entry.name}.fromJson(Map<String, dynamic> json) {`);
  out.push(`    return ${entry.name}(`);
  for (const f of entry.fields) {
    out.push(`      ${f.name}: ${read(f.type, `json[${quote(f.wire)}]`)},`);
  }
  out.push('    );');
  out.push('  }');
  out.push('');

  for (const f of entry.fields) {
    out.push(...docComment(f.description, '  '));
    if (f.wire !== f.name) {
      if (f.description) out.push('  ///');
      out.push(`  /// Wire key: \`${f.wire}\`.`);
    }
    out.push(`  final ${render(f.type)} ${f.name};`);
    out.push('');
  }

  out.push('  /// This value as JSON, with every null key left out.');
  out.push('  Map<String, dynamic> toJson() {');
  out.push('    final json = <String, dynamic>{};');
  for (const f of entry.fields) {
    const value = write(f.type, f.name);
    if (!f.type.nullable) {
      out.push(`    json[${quote(f.wire)}] = ${value};`);
    } else if (f.type.kind === 'stringList') {
      // A single language goes out as the string the gateway documents.
      out.push(`    final ${f.name} = this.${f.name};`);
      out.push(`    if (${f.name} != null) {`);
      out.push(
        `      json[${quote(f.wire)}] = ${f.name}.length == 1 ? ${f.name}.first : ${f.name};`,
      );
      out.push('    }');
    } else if (writesPlainly(f.type)) {
      out.push(`    if (${f.name} != null) {`);
      out.push(`      json[${quote(f.wire)}] = ${f.name};`);
      out.push('    }');
    } else {
      // A local, so the `.toJson()` mapping needs no `?.` inside a null check.
      out.push(`    final ${f.name} = this.${f.name};`);
      out.push(`    if (${f.name} != null) {`);
      out.push(`      json[${quote(f.wire)}] = ${write({ ...f.type, nullable: false }, f.name)};`);
      out.push('    }');
    }
  }
  out.push('    return json;');
  out.push('  }');
  out.push('}');
  return out.join('\n');
}

/**
 * A holder of the string constants an enum property accepts.
 *
 * Enums stay `String` on the fields themselves — the gateway adds values
 * between SDK releases and a Dart enum would turn that into a crash — but the
 * values it lists today are worth spelling once so callers can autocomplete
 * them instead of quoting a slug from the docs.
 */
function emitConstants(name, description, values) {
  const out = [];
  out.push(...docComment(description));
  out.push(`abstract final class ${name} {`);
  for (const value of values) {
    out.push(`  /// \`${value}\``);
    out.push(`  static const String ${camel(value)} = ${quote(value)};`);
    out.push('');
  }
  out.push('  /// Every value the snapshot lists, in its order.');
  out.push(`  static const List<String> values = <String>[`);
  for (const value of values) out.push(`    ${quote(value)},`);
  out.push('  ];');
  out.push('}');
  return out.join('\n');
}

/** A document that is a bare map: the class wraps it and subscripts through. */
function emitMapClass(entry, out) {
  const value = render(entry.valueType);
  const mapType = `Map<String, ${value}>`;
  out.push(`  /// Wraps the [values] this document is.`);
  out.push(`  const ${entry.name}(this.values);`);
  out.push('');
  out.push(`  /// Reads the map, keyed as the API keys it.`);
  out.push(`  factory ${entry.name}.fromJson(Map<String, dynamic> json) {`);
  out.push(`    return ${entry.name}(`);
  out.push(`      json.map((k, v) => MapEntry(k, ${read(entry.valueType, 'v')})),`);
  out.push('    );');
  out.push('  }');
  out.push('');
  out.push('  /// The document itself, which has no fields of its own.');
  out.push(`  final ${mapType} values;`);
  out.push('');
  out.push('  /// The entry under [key], or null when the API left it out.');
  out.push(`  ${value}${entry.valueType.nullable ? '' : '?'} operator [](String key) =>`);
  out.push('      values[key];');
  out.push('');
  out.push('  /// This value as JSON.');
  out.push('  Map<String, dynamic> toJson() =>');
  const inner = write(entry.valueType, 'v');
  out.push(
    inner === 'v'
      ? '      Map<String, dynamic>.from(values);'
      : `      values.map((k, v) => MapEntry(k, ${inner}));`,
  );
  out.push('}');
  return out.join('\n');
}

