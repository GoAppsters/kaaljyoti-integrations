/**
 * A resolved Dart type.
 *
 * `kind` drives the `fromJson` / `toJson` expressions; `dart` is what the
 * field is declared as. `nullable` is tracked separately from `dart` so a
 * `List<T>?` knows its element type is not itself nullable.
 */
function type(kind, extra = {}) {
  return { kind, nullable: false, ...extra };
}

function render(t) {
  const q = t.nullable ? '?' : '';
  switch (t.kind) {
    case 'string':
      return `String${q}`;
    case 'int':
      return `int${q}`;
    case 'double':
      return `double${q}`;
    case 'bool':
      return `bool${q}`;
    case 'stringList':
      return `List<String>${q}`;
    case 'class':
    case 'union':
      return `${t.name}${q}`;
    case 'list':
      return `List<${render(t.of)}>${q}`;
    case 'map':
      return `Map<String, ${render(t.of)}>${q}`;
    case 'json':
      return `Map<String, dynamic>${q}`;
    case 'any':
      return 'Object?';
    default:
      throw new Error(`unknown kind ${t.kind}`);
  }
}

/** The expression that reads `expr` (an `Object?`) as a non-null `t`. */
function readNonNull(t, expr) {
  switch (t.kind) {
    case 'string':
      return `asString(${expr})`;
    case 'int':
      return `asInt(${expr})`;
    case 'double':
      return `asDouble(${expr})`;
    case 'bool':
      return `asBool(${expr})`;
    case 'stringList':
      return `asStringList(${expr})`;
    case 'class':
      return `${t.name}.fromJson(asMap(${expr}))`;
    case 'union':
      return `${t.name}.fromJson(${expr})`;
    case 'json':
      return `asMap(${expr})`;
    case 'any':
      return expr;
    case 'list': {
      const inner = read(t.of, 'e');
      return inner === 'e' ? `asList(${expr})` : `asList(${expr}).map((e) => ${inner}).toList()`;
    }
    case 'map': {
      const inner = read(t.of, 'v');
      return inner === 'v'
        ? `asMap(${expr})`
        : `asMap(${expr}).map((k, v) => MapEntry(k, ${inner}))`;
    }
    default:
      throw new Error(`unknown kind ${t.kind}`);
  }
}

/** The expression that reads `expr` as `t`, nullability included. */
function read(t, expr) {
  if (!t.nullable) return readNonNull(t, expr);
  if (t.kind === 'any') return expr;
  const simple = {
    string: 'asStringOrNull',
    int: 'asIntOrNull',
    double: 'asDoubleOrNull',
    bool: 'asBoolOrNull',
  };
  if (simple[t.kind]) return `${simple[t.kind]}(${expr})`;
  return `${expr} == null ? null : ${readNonNull(t, expr)}`;
}

/** The expression that turns the field `name` of type `t` back into JSON. */
function write(t, name) {
  const q = t.nullable ? '?' : '';
  switch (t.kind) {
    case 'class':
    case 'union':
      return `${name}${q}.toJson()`;
    case 'list':
      return writesPlainly(t.of) ? name : `${name}${q}.map((e) => ${write(t.of, 'e')}).toList()`;
    case 'map':
      return writesPlainly(t.of)
        ? name
        : `${name}${q}.map((k, v) => MapEntry(k, ${write(t.of, 'v')}))`;
    default:
      return name;
  }
}

/** True when a value of `t` is already JSON and needs no mapping. */
function writesPlainly(t) {
  return ['string', 'int', 'double', 'bool', 'json', 'any', 'stringList'].includes(t.kind);
}

