/** `utc_offset` / `UtcOffset` / `utcOffset` → `['utc', 'offset']`. */
function words(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
}

function pascal(name) {
  return words(name)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');
}

function camel(name) {
  const p = pascal(name);
  const lower = p[0].toLowerCase() + p.slice(1);
  return RESERVED.has(lower) ? `${lower}Value` : lower;
}

