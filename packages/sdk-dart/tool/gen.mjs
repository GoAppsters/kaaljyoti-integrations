/**
 * Resolve one schema to a Dart type, defining classes as it goes.
 *
 * `hint` is the name a class would get if this schema turns out to need one:
 * the owning class plus the property, so `KundliDocument.birth` is
 * `KundliDocumentBirth` and the value type of its `positions` map is
 * `KundliDocumentPositionsValue`.
 */
function resolve(schema, hint, origin) {
  if (!schema || typeof schema !== 'object') return type('any');
  if (schema.$ref) return type('class', { name: refName(schema.$ref) });

  if (schema.anyOf) return resolveAnyOf(schema, hint, origin);

  const declared = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  const nullable = declared.includes('null');
  const rest = declared.filter((t) => t !== 'null');

  if (rest.length === 0 && nullable) {
    // `{"type": "null"}`: the engine always answers null here (choghadiya's
    // `planet`). There is no Dart type for "always null" worth having, so the
    // field is an `Object?` the caller can ignore.
    fallbacks.push(`${origin}: \`type: "null"\` → Object?`);
    return type('any', { nullable: true });
  }
  if (rest.length > 1) {
    fallbacks.push(`${origin}: \`type: ${JSON.stringify(declared)}\` → Object?`);
    return type('any', { nullable: true });
  }

  const base = rest[0] ?? (schema.properties ? 'object' : schema.items ? 'array' : undefined);
  let resolved;
  switch (base) {
    case 'string':
      resolved = type('string');
      break;
    case 'integer':
      resolved = type('int');
      break;
    case 'number':
      // `number` is `double`, except where the schema enumerates whole
      // numbers (`levels: 1 | 2 | 3 | 4 | 5`) and an int reads better on the wire.
      resolved = type(allIntegerEnum(schema) ? 'int' : 'double');
      break;
    case 'boolean':
      resolved = type('bool');
      break;
    case 'array':
      resolved = type('list', { of: resolve(schema.items, `${hint}Item`, `${origin}[]`) });
      break;
    case 'object':
      resolved = resolveObject(schema, hint, origin);
      break;
    default:
      fallbacks.push(`${origin}: no \`type\` → Object?`);
      resolved = type('any', { nullable: true });
  }
  return nullable ? { ...resolved, nullable: true } : resolved;
}

function allIntegerEnum(schema) {
  return Array.isArray(schema.enum) && schema.enum.every((v) => Number.isInteger(v));
}

function resolveObject(schema, hint, origin) {
  if (schema.properties) return type('class', { name: defineClass(schema, hint, origin) });
  const extra = schema.additionalProperties;
  if (extra && typeof extra === 'object') {
    return type('map', { of: resolve(extra, `${hint}Value`, `${origin}{}`) });
  }
  // `additionalProperties: true`, or no properties at all: an open row.
  return type('json');
}

function resolveAnyOf(schema, hint, origin) {
  const branches = schema.anyOf;
  const isNull = (b) =>
    b.type === 'null' ||
    (Array.isArray(b.type) && !b.type.includes('object') && b.type.every((t) => t === 'null'));
  const nullable =
    branches.some(isNull) || branches.some((b) => Array.isArray(b.type) && b.type.includes('null'));
  const real = branches.filter((b) => !isNull(b));

  // `options.language`: `'en'` or `['en', 'hi']` on the wire. Callers get one
  // type — a list — and a single-element list goes out as the bare string.
  const stringOrList =
    real.length === 2 &&
    real.some((b) => b.type === 'string') &&
    real.some((b) => b.type === 'array' && b.items?.type === 'string');
  if (stringOrList) return type('stringList', { nullable });

  if (UNION_NAMES[origin]) return type('union', { name: UNION_NAMES[origin], nullable: true });

  if (real.length === 1) return { ...resolve(real[0], hint, origin), nullable: true };

  // `levels: 1 | 2 | 3 | 4 | 5` arrives as five single-value `number` branches.
  if (real.length > 1 && real.every((b) => b.type === 'number' && allIntegerEnum(b))) {
    return type('int', { nullable });
  }
  if (real.length > 1 && real.every((b) => b.type === real[0].type && !b.properties)) {
    return { ...resolve(real[0], hint, origin), nullable };
  }

  fallbacks.push(`${origin}: \`anyOf\` of ${real.length} unrelated shapes → Object?`);
  return type('any', { nullable: true });
}

/**
 * Define (or reuse) the class for an object schema and answer its name.
 *
 * Equal shapes share a class, which is what keeps `Birth` and
 * `CalculationOptions` single classes instead of 35 copies apiece.
 */
function defineClass(schema, preferred, origin) {
  const key = shapeKey(schema);
  const existing = shapes.get(key);
  if (existing) return existing;

  let name = NESTED_RENAMES[preferred] ?? preferred;
  if (classes.has(name)) {
    let n = 2;
    while (classes.has(`${name}${n}`)) n += 1;
    fallbacks.push(`${origin}: name ${name} was taken → ${name}${n}`);
    name = `${name}${n}`;
  }

  const entry = {
    name,
    description: DESCRIPTIONS[name] ?? schema.description,
    origin,
    fields: [],
  };
  classes.set(name, entry);
  shapes.set(key, name);

  if (!schema.properties) {
    // A document that is a bare map (`MaitriDocument` is planet → planet →
    // relation). Dart has no place to hang `fromJson` on a `Map`, so the class
    // wraps the map and subscripts through to it; `toJson` still answers the
    // map itself, so the wire shape is unchanged.
    entry.valueType = resolve(
      schema.additionalProperties && typeof schema.additionalProperties === 'object'
        ? schema.additionalProperties
        : {},
      `${name}Value`,
      `${origin}{}`,
    );
    return name;
  }

  const required = new Set(schema.required ?? []);
  const used = new Map();
  for (const [wire, propSchema] of Object.entries(schema.properties)) {
    let dartName = camel(wire);
    if (used.has(dartName)) {
      fallbacks.push(
        `${name}: \`${wire}\` and \`${used.get(dartName)}\` both camelCase to ${dartName}`,
      );
      dartName = `${dartName}${pascal(wire)}`;
    }
    used.set(dartName, wire);
    const fieldType = resolve(propSchema, name + pascal(wire), `${name}.${wire}`);
    entry.fields.push({
      wire,
      name: dartName,
      description: DESCRIPTIONS[`${name}.${wire}`] ?? propSchema.description,
      // Anything the schema does not require, and anything it requires but
      // allows to be null, is a `T?` in Dart: the gateway omits keys it has
      // nothing to say about.
      type: { ...fieldType, nullable: fieldType.nullable || !required.has(wire) },
    });
  }
  return name;
}

