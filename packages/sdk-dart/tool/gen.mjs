#!/usr/bin/env node
/**
 * `openapi/openapi.json` → `lib/src/generated/*.dart`.
 *
 * Design decision 1: our own generator. `openapi-generator`'s Dart output
 * drags in `built_value` or `dio`; `json_serializable` would force
 * `build_runner` on every consumer of the SDK. This emits plain Dart —
 * immutable classes with `final` fields, a `fromJson` factory and a `toJson`
 * that omits nulls — and nothing a caller has to install.
 *
 * What it writes:
 *
 *   lib/src/generated/_json.dart       cast helpers (`strict-casts` is on)
 *   lib/src/generated/labelled_id.dart the one shape every document shares
 *   lib/src/generated/models.dart      every request, document and nested class
 *   lib/src/generated/operations.dart  the operation table the contract test walks
 *   lib/src/generated/version.dart     the two version constants
 *
 * The output is committed so a reader of the package can see the shapes
 * without running anything; `--check` regenerates into `.dart_tool/`, formats
 * that copy the same way, and compares byte for byte, so CI fails on a stale
 * file rather than shipping models that describe an API we no longer have.
 *
 * Usage: `node tool/gen.mjs [--check]`.
 */

